#!/usr/bin/env bash
# mtg-table — diff the Forge API the bridge compiles against, between two jars.
# Copyright (C) 2026 mtg-table contributors.
# SPDX-License-Identifier: GPL-3.0-or-later
#
# The question this answers on the day a new Forge release lands: "did the seam
# move since the snapshot our saved port was written against?"  It is spike B's
# javap recipe (docs/evidence/engine-upgrade.md, "The javap diff") as a script:
#
#   classes = every `import forge.*` under bridge/src, plus the eight classes the
#             bridge reaches without importing (listed in EXTRA below);
#   for each class and each jar: javap (non-private members), minus the
#             "Compiled from" line, sorted;
#   print   = per class, the lines only in OLD ("<") and only in NEW (">"), then
#             the list of classes whose javap is identical.
#
# READ-ONLY.  It runs javap and writes nothing but stdout (and a temp dir under
# the session's TMPDIR that it removes).  It never touches forge-home/, var/ or
# either jar's directory.
#
# Usage (from the repo root, hard rule 9):
#
#   ./tools/javap-seam-diff.sh <old.jar> <new.jar>
#   ./tools/javap-seam-diff.sh "$FORGE_JAR" var/forge-engine/<v>/forge-gui-desktop-<v>-jar-with-dependencies.jar
#
# On the day, compare its output against the snapshot's, which is saved beside
# the port it justified:
#
#   ./tools/javap-seam-diff.sh /home/justin-a/forge/forge-gui-desktop-2.0.14-jar-with-dependencies.jar \
#       <release jar> > var/javap-release.txt
#   diff <(sed 1,3d docs/research/patches/javap-2.0.14-vs-2.0.15-snapshot-09.27.txt) \
#        <(sed 1,3d var/javap-release.txt)
#
# No difference means docs/research/patches/bridge-forge-2.0.15-snapshot-09.27.patch
# was written against the seam the release has.  Any difference in IGuiGame,
# AbstractGuiGame, IGameController, InputPassPriority or PlayerControllerHuman
# means re-port by the same method before applying anything.
#
# Exit: 0 printed a diff (identical or not), 2 usage or javap failure.
set -euo pipefail

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/config.sh"

[ $# -eq 2 ] || { echo "usage: $0 <old.jar> <new.jar>" >&2; exit 2; }
OLD=$1 NEW=$2
for j in "$OLD" "$NEW"; do [ -f "$j" ] || { echo "not a file: $j" >&2; exit 2; }; done

# The bridge reaches these without an import line of its own: a nested class, a
# supertype whose members it overrides or calls, or a class it names only in a
# comment-justified cast.  Spike B's list, unchanged.
EXTRA=(
  'forge.gamemodes.match.YieldController'
  'forge.game.card.CardView$CardStateView'
  'forge.game.event.IGameEventVisitor'
  'forge.game.event.IGameEventVisitor$Base'
  'forge.game.player.PlayerController'
  'forge.gui.control.FControlGamePlayback'
  'forge.gamemodes.match.input.InputPassPriority'
  'forge.game.GameEntityView'
)

mapfile -t CLASSES < <(
  { grep -hoE '^import forge\.[A-Za-z0-9_.]+;' "$REPO_ROOT"/bridge/src/mtgtable/*.java \
      | sed -E 's/^import (.*);$/\1/' \
      | awk -F. '{ o = $1; n = ($1 ~ /^[A-Z]/)            # a nested import
                   for (i = 2; i <= NF; i++) {             # (ForgePreferences.FPref)
                     o = o (n ? "$" : ".") $i              # is javap binary name
                     if ($i ~ /^[A-Z]/) n = 1 }            # ForgePreferences$FPref
                   print o }'
    printf '%s\n' "${EXTRA[@]}"; } | sort -u)

WORK=$(mktemp -d "${TMPDIR:-/tmp}/javap-seam-diff.XXXXXX")
trap 'rm -rf "$WORK"' EXIT

# One javap per jar for every class; split its output per class on the
# "Compiled from" line and name each block by its own declaration line, so a
# class missing from one jar cannot shift the others.
dump() {  # dump <jar> <outdir>
  mkdir -p "$2"
  java -m jdk.jdeps/com.sun.tools.javap.Main -cp "$1" "${CLASSES[@]}" 2>"$2.err" \
    | awk -v dir="$2" '
        /^Compiled from / { getline decl
                            match(decl, /(class|interface|enum|record) [A-Za-z0-9_.$]+/)
                            name = substr(decl, RSTART, RLENGTH); sub(/^[a-z]+ /, "", name)
                            out = dir "/" name; print decl > out; next }
        out != "" { sub(/^ +/, ""); print > out }' || true
  local f n=0
  for f in "$2"/*; do [ -f "$f" ] || continue; sort -o "$f" "$f"; n=$((n + 1)); done
  [ "$n" -gt 0 ] || { echo "javap loaded no class from $1:" >&2
                      head -3 "$2.err" >&2; exit 2; }
}
dump "$OLD" "$WORK/old"
dump "$NEW" "$WORK/new"

ver() { unzip -p "$1" META-INF/MANIFEST.MF 2>/dev/null | tr -d '\r' \
          | sed -n 's/^Implementation-Version: //p' | head -1; }
echo "# javap diff: $(ver "$OLD") (<) vs $(ver "$NEW") (>), non-private members, sorted"
echo "# classes: ${#CLASSES[@]} -- every forge.* class bridge/src imports, plus ${EXTRA[*]##*.}"
echo "# generated by tools/javap-seam-diff.sh"

same=()
missing=()
for c in "${CLASSES[@]}"; do
  o="$WORK/old/$c" n="$WORK/new/$c"
  if [ ! -f "$o" ] && [ ! -f "$n" ]; then missing+=("$c (absent in both)"); continue; fi
  if [ ! -f "$o" ]; then missing+=("$c (absent in old)"); continue; fi
  if [ ! -f "$n" ]; then missing+=("$c (absent in new)"); continue; fi
  if cmp -s "$o" "$n"; then same+=("$c"); continue; fi
  echo
  echo "== $c"
  diff "$o" "$n" | grep -E '^[<>]' || true
done
if [ ${#missing[@]} -gt 0 ]; then
  echo
  echo "== missing (javap could not load the class from one jar):"
  printf '   %s\n' "${missing[@]}"
fi
echo
echo "== unchanged (identical javap): ${#same[@]}"
printf '   %s\n' "${same[@]}"
