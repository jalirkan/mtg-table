// Tuning and confirming on the same ten deck pairs (tools/ai-bench/pairs-cube.txt,
// two cubes) would select settings that exploit those decks (D318).  So the
// ladder has two generated sets, drawn from cube-lab drafts across the cubes:
//
//   tools/ai-bench/pairs-dev.txt       tuning, pilots, exploration (`tune`'s default)
//   tools/ai-bench/pairs-confirm.txt   promotion and published numbers (`run`,
//                                      `sprt`, `league`, `ratings`, `report`)
//
// with their decks under tools/ai-bench/decks/sets/<cube>-<seed>-<A|B>.dck.
// `ai-ladder.sh decksets` drafts with the lab (`cubelab.sh run --games 0`: two
// AI drafters, the lab's builder, no games) on each cube, then `collect()` takes
// every draft whose two lab decks were built, sorts each cube's drafts by seed
// and deals them alternately to dev and confirm — a pure function of the run
// folders, so the split is reproducible.  Never tune on the confirm set.

import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';

export interface SetPair { cube: string; seed: number; a: string; b: string }

/** The drafts of one cubelab run folder whose two lab decks exist: [cube, seed, deckA, deckB]. */
export function draftsOf(runDir: string): SetPair[] {
  const meta = JSON.parse(readFileSync(join(runDir, 'run.json'), 'utf8')) as { cube: string; cubeFile: string };
  const cube = basename(meta.cubeFile).replace(/\.md$/, '').replace(/-cube-\d+$/, '').replace(/-\d+$/, '');
  const out: SetPair[] = [];
  const f = join(runDir, 'drafts.jsonl');
  if (!existsSync(f)) return out;
  for (const line of readFileSync(f, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    const r = JSON.parse(line) as { seed: number; drafters: Array<{ deckFile: string | null }> };
    const [x, y] = r.drafters;
    if (!x?.deckFile || !y?.deckFile) continue;
    const a = join(runDir, x.deckFile), b = join(runDir, y.deckFile);
    if (existsSync(a) && existsSync(b)) out.push({ cube, seed: r.seed, a, b });
  }
  return out;
}

/** Per cube, by seed: even positions to dev, odd to confirm. */
export function split(pairs: SetPair[]): { dev: SetPair[]; confirm: SetPair[] } {
  const byCube = new Map<string, SetPair[]>();
  for (const p of pairs) byCube.set(p.cube, [...(byCube.get(p.cube) ?? []), p]);
  const dev: SetPair[] = [], confirm: SetPair[] = [];
  for (const cube of [...byCube.keys()].sort()) {
    const ps = (byCube.get(cube) as SetPair[]).sort((x, y) => x.seed - y.seed);
    ps.forEach((p, i) => (i % 2 === 0 ? dev : confirm).push(p));
  }
  return { dev, confirm };
}

/** Copy the decks into the repo and write the two pairs files; returns the lines written. */
export function writeSets(repo: string, sets: { dev: SetPair[]; confirm: SetPair[] }, note: string): { dev: number; confirm: number } {
  const deckDir = join(repo, 'tools/ai-bench/decks/sets');
  mkdirSync(deckDir, { recursive: true });
  for (const [name, ps] of Object.entries(sets) as Array<['dev' | 'confirm', SetPair[]]>) {
    const lines = [
      `# tools/ai-bench/pairs-${name}.txt -- the AI ladder's ${name.toUpperCase()} deck set (D318), generated by`,
      '# `tools/ai-ladder.sh decksets`: cube-lab drafts (two AI drafters, the lab builder),',
      '# each cube\'s drafts dealt alternately to dev and confirm.' + (name === 'confirm' ? ' NEVER tune on this set.' : ' Tune and explore here.'),
      `# ${note}`,
    ];
    for (const p of ps) {
      const da = join(deckDir, `${p.cube}-${p.seed}-A.dck`), db = join(deckDir, `${p.cube}-${p.seed}-B.dck`);
      copyFileSync(p.a, da);
      copyFileSync(p.b, db);
      lines.push(`${relative(repo, da)} ${relative(repo, db)}   # ${p.cube} seed ${p.seed}`);
    }
    writeFileSync(join(repo, `tools/ai-bench/pairs-${name}.txt`), lines.join('\n') + '\n');
  }
  return { dev: sets.dev.length, confirm: sets.confirm.length };
}
