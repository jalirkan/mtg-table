#
# Forge derives EVERY path it reads or writes from IGuiBase.getAssetsDir():
#
#     ASSETS_DIR   = getAssetsDir()                       -> <repo>/forge-home/
#     PROFILE_FILE = ASSETS_DIR + "forge.profile.properties"
#     RES_DIR      = ASSETS_DIR + "res/"                  -> symlink, read-only
#     USER_DIR     = ForgeProfileProperties.getUserDir()  -> <repo>/var/forge/
#     CACHE_DIR    = ForgeProfileProperties.getCacheDir() -> <repo>/var/cache/
#
# (forge-gui/src/main/java/forge/localinstance/properties/ForgeConstants.java:37,232-240)
#
# Without the profile file, ForgeProfileProperties.getDefaultDirs() falls back to
# $HOME/.forge and $HOME/.cache/forge on Linux
# (ForgeProfileProperties.java:179-203) and FModel.initialize would create 24
# profile directories inside the user's real Forge installation.  That is exactly
# what this script prevents.
#
# This script writes ONLY under the repo.  It never writes inside the Forge
# installation it reads res/ from.
#
# Usage:  ./tools/make-forge-home.sh
set -euo pipefail

. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/config.sh"

# The resource tree is derived from the jar path, not hardcoded: config.json's
# forgeJar (or $FORGE_JAR) already names the one Forge installation this repo
# talks to, and res/ sits beside the jar in it.  Hardcoding a second path was a
# way for the two to disagree silently after the user moved their install.
FORGE_INSTALL="$(cd "$(dirname "$FORGE_JAR")" && pwd)"
FORGE_RES="$FORGE_INSTALL/res"

[ -d "$FORGE_RES" ] || {
  echo "Forge res/ not found: $FORGE_RES"
  echo "  (derived from forgeJar = $FORGE_JAR; res/ is expected beside the jar)"
  exit 1
}

# Refuse to run if the repo root somehow points inside the Forge installation
# (or the user's real profile), which is the one thing this script must never
# write to.
case "$REPO_ROOT/" in
  "$FORGE_INSTALL"/*|"$HOME"/.forge/*)
    echo "refusing to write inside the Forge installation: $REPO_ROOT"; exit 1;;
esac

mkdir -p "$REPO_ROOT/forge-home" "$REPO_ROOT/var/forge" "$REPO_ROOT/var/cache"

# -n so that re-pointing an existing symlink replaces the link itself rather
# than creating res/res inside the directory it points at.
ln -sfn "$FORGE_RES" "$REPO_ROOT/forge-home/res"

# ForgeProfileProperties.getDir() (ForgeProfileProperties.java:140-155) does
# new File(value).getAbsolutePath() and then appends File.separatorChar if it is
# missing, so a trailing slash here is cosmetic -- but a RELATIVE path would be
# resolved against the JVM's working directory, which is why these are absolute.
# Backslashes would need escaping in a .properties file; there are none on Linux.
cat > "$REPO_ROOT/forge-home/forge.profile.properties" <<EOF
# Generated by tools/make-forge-home.sh -- do not edit by hand, re-run the script.
# Gitignored: it carries absolute paths and is regenerated per checkout.
# Keeps every byte Forge writes inside <repo>/var/ instead of ~/.forge and
# ~/.cache/forge.  Recognised keys: userDir, cacheDir, cardPicsDir,
# cardPicsSubDirs, decksDir, decksConstructedDir
# (ForgeProfileProperties.java:47-52).  decksDir defaults to <userDir>/decks/ and
# cardPicsDir to <cacheDir>/pics/cards/, so those two keys are enough.
userDir=$REPO_ROOT/var/forge/
cacheDir=$REPO_ROOT/var/cache/
EOF

# --------------------------------------------------------------------------
# Card-script overlay (decision D14, docs/research/08-deck-card-coverage.md §2).
#
# Forge reads card scripts from TWO trees: res/cardsfolder (read-only, inside
# the user's install, which we must never write to) and a user overlay at
#     USER_CUSTOM_CARDS_DIR = USER_DIR + "custom/cards/"
# (ForgeConstants.java:253-255).  StaticData loads the stock tree first and then
# the overlay into the SAME map (StaticData.java:113-131, :287-302), so a file
# with the same Name: silently wins.
#
# USER_CUSTOM_CARDS_DIR is NOT in ForgeConstants.PROFILE_DIRS, so FModel does not
# create it -- and CardStorageReader THROWS when its directory is missing, which
# FModel swallows into customReader = null (FModel.java:214-222).  A missing
# directory therefore means "no overlay", silently.  Hence the mkdir.
#
# var/ is gitignored, so the committed source of truth is forge-home/custom-cards/
# and this copy is what makes it take effect.
# --------------------------------------------------------------------------
CUSTOM_SRC="$REPO_ROOT/forge-home/custom-cards"
CUSTOM_DST="$REPO_ROOT/var/forge/custom/cards"
mkdir -p "$CUSTOM_DST"
custom_n=0
if [ -d "$CUSTOM_SRC" ]; then
  for f in "$CUSTOM_SRC"/*.txt; do
    [ -e "$f" ] || continue
    cp -f "$f" "$CUSTOM_DST/"
    custom_n=$((custom_n + 1))
  done
fi

echo "forge home:  $REPO_ROOT/forge-home/"
echo "  res     -> $(readlink -f "$REPO_ROOT/forge-home/res")"
echo "  userDir  = $REPO_ROOT/var/forge/"
echo "  cacheDir = $REPO_ROOT/var/cache/"
echo "  custom   = $CUSTOM_DST ($custom_n card script(s) copied)"
echo "forge home OK"
